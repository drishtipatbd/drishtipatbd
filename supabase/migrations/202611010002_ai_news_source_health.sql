-- Persist per-feed health telemetry for the AI newsroom.
-- Additive only. This migration is authored for review and is NOT applied automatically.

create table if not exists public.ai_news_source_runs (
  id bigint generated by default as identity primary key,
  run_id uuid not null,
  source_id text not null,
  publisher_id text not null,
  domain text not null,
  status text not null check (status in ('ok', 'no_fresh_items', 'error')),
  checked_at timestamptz not null,
  items_found integer not null default 0 check (items_found >= 0),
  freshness_window_hours integer not null default 72 check (freshness_window_hours between 1 and 168),
  error_message text not null default '',
  created_at timestamptz not null default now(),
  constraint ai_news_source_runs_run_source_unique unique (run_id, source_id)
);

create index if not exists ai_news_source_runs_source_checked_idx
  on public.ai_news_source_runs (source_id, checked_at desc);

create index if not exists ai_news_source_runs_status_checked_idx
  on public.ai_news_source_runs (status, checked_at desc);

alter table public.ai_news_source_runs enable row level security;

drop policy if exists "Admins can read AI newsroom source health" on public.ai_news_source_runs;
create policy "Admins can read AI newsroom source health"
  on public.ai_news_source_runs
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.admin_users au
      where au.user_id = auth.uid()
        and au.role = 'admin'
    )
  );

comment on table public.ai_news_source_runs is
  'Per-feed health telemetry for AI newsroom runs. Inserts are performed only by the server-side service role; admin users may read.';
