-- DrishtipatBD public opinion moderation table. Apply only after selecting the intended Supabase project.
create table if not exists public.public_opinions (
 id bigint generated by default as identity primary key,
 name text not null check (char_length(name) between 2 and 100),
 address text not null check (char_length(address) between 2 and 250),
 body text not null check (char_length(body) between 2 and 3000),
 photo_url text,
 status text not null default 'pending' check (status in ('pending','approved','rejected')),
 created_at timestamptz not null default now()
);
alter table public.public_opinions enable row level security;
drop policy if exists "Public can submit pending opinions" on public.public_opinions;
create policy "Public can submit pending opinions" on public.public_opinions for insert to anon, authenticated with check (status='pending');
drop policy if exists "Public can read approved opinions" on public.public_opinions;
create policy "Public can read approved opinions" on public.public_opinions for select to anon, authenticated using (status='approved');
drop policy if exists "Admins can manage opinions" on public.public_opinions;
create policy "Admins can manage opinions" on public.public_opinions for all to authenticated using (exists(select 1 from public.admin_users u where u.user_id=auth.uid() and u.role='admin')) with check (exists(select 1 from public.admin_users u where u.user_id=auth.uid() and u.role='admin'));
