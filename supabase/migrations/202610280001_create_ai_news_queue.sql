-- AI News Desk queue for DristipatBD.
-- Additive migration; does not alter existing articles or publication behavior.
create table if not exists public.ai_news_queue (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text,
  excerpt text not null default '',
  body text not null default '',
  image_url text not null default '',
  category_id bigint references public.categories(id) on delete set null,
  source_name text not null default '',
  source_url text not null,
  source_published_at timestamptz,
  news_type text not null default 'general' check (news_type in ('general','breaking','sports','domestic','international')),
  workflow_status text not null default 'pending' check (workflow_status in ('pending','approved','published','rejected','failed')),
  auto_publish boolean not null default false,
  verification_status text not null default 'needs_review' check (verification_status in ('needs_review','verified','conflicting','unverified')),
  dedupe_key text not null unique,
  verification_notes text not null default '',
  published_article_id bigint references public.articles(id) on delete set null,
  error_message text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);
create index if not exists ai_news_queue_status_created_idx on public.ai_news_queue (workflow_status, created_at desc);
create index if not exists ai_news_queue_type_created_idx on public.ai_news_queue (news_type, created_at desc);
alter table public.ai_news_queue enable row level security;
drop policy if exists "staff manage AI news queue" on public.ai_news_queue;
create policy "staff manage AI news queue" on public.ai_news_queue
for all to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = (select auth.uid()) and au.role = 'admin'))
with check (exists (select 1 from public.admin_users au where au.user_id = (select auth.uid()) and au.role = 'admin'));
grant select, insert, update, delete on public.ai_news_queue to authenticated;
grant usage, select on sequence public.ai_news_queue_id_seq to authenticated;
